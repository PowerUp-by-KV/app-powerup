/**
 * Get location suggestions based on input
 * @param input - User input text
 * @returns Array of location suggestions
 */
export const getLocationSuggestions = (input: string): LocationSuggestion[] => {
  if (!input || input.length < 1) return [];

  const query = input.toLowerCase();
  const suggestions: LocationSuggestion[] = [];
  const seen = new Set<string>();

  // Search countries
  locations.countries.forEach((country) => {
    if (country.toLowerCase().includes(query)) {
      const id = `country-${country}`;
      if (!seen.has(id)) {
        seen.add(id);
        suggestions.push({
          id,
          name: country,
          type: "country",
          country,
          displayText: `${country}`,
        });
      }
    }
  });

  // Search states
  Object.entries(locations.states).forEach(([country, stateList]) => {
    stateList.forEach((stateObj) => {
      const state = stateObj.state;
      if (state.toLowerCase().includes(query)) {
        const id = `state-${country}-${state}`;
        if (!seen.has(id)) {
          seen.add(id);
          suggestions.push({
            id,
            name: state,
            type: "state",
            country,
            state,
            displayText: `${state} (${country})`,
          });
        }
      }
    });
  });

  // Search districts
  Object.entries(locations.districts).forEach(([state, districtList]) => {
    districtList.forEach((district) => {
      if (district.toLowerCase().includes(query)) {
        // Find country for this state
        let country = "India"; // Default
        Object.entries(locations.states).forEach(([c, states]) => {
          if (states.some((s) => s.state === state)) {
            country = c;
          }
        });

        const id = `district-${state}-${district}`;
        if (!seen.has(id)) {
          seen.add(id);
          suggestions.push({
            id,
            name: district,
            type: "district",
            country,
            state,
            district,
            displayText: `${district}, ${state} (${country})`,
          });
        }
      }
    });
  });

  // Sort by type (district first as most specific, then state, then country)
  const typeOrder = { district: 0, area: 1, state: 2, country: 3 };
  suggestions.sort((a, b) => typeOrder[a.type] - typeOrder[b.type]);

  return suggestions.slice(0, 10); // Return top 10 suggestions
};

/**
 * Format location selection into a display string
 */
export const formatLocationDisplay = (suggestion: LocationSuggestion): string => {
  return suggestion.displayText;
};
